/*
===============================================================================
프로젝트 : 운영 기준 전환 A/B Test
DB     : Amazon Athena / Presto SQL

목적
----
NAU 기반 운영 기준 산출에 필요한 콘텐츠별 성과 지표를 추출합니다.

공개용 코드 안내
----------------
- 실제 프로젝트에서 사용한 분석 로직을 기반으로 공개용으로 리팩터링했습니다.
- 내부 DB명, 테이블명, 콘텐츠 ID, 사용자 식별자 등은 익명화했습니다.
- 예시 콘텐츠 ID와 테이블명은 포트폴리오용 임의 값입니다.
- 실제 회사 데이터 및 개인 식별 정보는 포함하지 않습니다.

집계 기준
---------
- 모든 지표는 국가 × 콘텐츠 단위를 기준으로 산출합니다.
- 사용자 수 지표는 익명화된 사용자 식별자를 기준으로 중복 제거하여 집계합니다.
- 금액 및 이벤트 지표는 분석 기간 내 발생 데이터를 콘텐츠 단위로 집계합니다.

주요 지표
---------
NAU
    분석 기간 내 해당 콘텐츠를 처음 사용한 신규 활성 사용자 수
    동일 사용자는 콘텐츠별로 1명으로 집계합니다.

AU
    분석 기간 내 해당 콘텐츠를 사용한 전체 활성 사용자 수
    동일 사용자는 콘텐츠별로 중복 제거하여 집계합니다.

NAU Ratio
    전체 활성 사용자 중 신규 활성 사용자가 차지하는 비율
    NAU / AU 로 계산합니다.

Download
    분석 기간 내 해당 콘텐츠에서 발생한 다운로드 이벤트 수입니다.

Revenue
    분석 기간 내 해당 콘텐츠에서 발생한 구매 금액의 합계입니다.

PU
    분석 기간 내 해당 콘텐츠에서 매출을 발생시킨 고유 사용자 수입니다.
    기간 내 동일 사용자의 반복 구매는 사용자 수 기준으로 중복 제거합니다.

ARPPU
    구매 사용자 1명당 평균 구매 금액입니다.
    Revenue / PU 로 계산합니다.
===============================================================================
*/

/* ---------------------------------------------------------------------------
1. Analysis period
--------------------------------------------------------------------------- */
WITH
params AS (
    SELECT
        DATE '2025-07-17' AS start_date,
        DATE '2025-07-23' AS end_date
),


/* ---------------------------------------------------------------------------
2. Target contents

Actual content IDs used in the business environment were removed.
The values below are synthetic examples for portfolio use.
--------------------------------------------------------------------------- */

target_content (
    country_code,
    content_id
) AS (

    VALUES
        ('KOR', 'content_001'),
        ('KOR', 'content_002'),
        ('KOR', 'content_003'),
        ('BRA', 'content_101'),
        ('BRA', 'content_102'),
        ('BRA', 'content_103')
),


/* ---------------------------------------------------------------------------
3. Content metadata

Retrieve content name and first sales/listing date.
--------------------------------------------------------------------------- */

content_metadata AS (

    SELECT
        tc.country_code,
        tc.content_id,
        cm.content_name,
        CAST(cm.created_at AS DATE) AS first_sales_date

    FROM target_content AS tc

    LEFT JOIN "sample_catalog"."content_master" AS cm
        ON tc.content_id = cm.content_id
),


/* ---------------------------------------------------------------------------
4. NAU

Count users whose first use occurred during the analysis period.
--------------------------------------------------------------------------- */

new_users AS (

    SELECT
        n.country_code,
        n.content_id,
        COUNT(DISTINCT n.user_id) AS nau

    FROM "sample_catalog"."new_user_activity" AS n

    INNER JOIN target_content AS tc
        ON n.country_code = tc.country_code
       AND n.content_id = tc.content_id

    CROSS JOIN params AS p

    WHERE CAST(n.first_use_date AS DATE)
          BETWEEN p.start_date AND p.end_date

    GROUP BY
        n.country_code,
        n.content_id
),


/* ---------------------------------------------------------------------------
5. Downloads

Count successful download events generated by each content.
--------------------------------------------------------------------------- */

downloads AS (

    SELECT
        d.country_code,
        d.content_id,
        COUNT(d.user_id) AS downloads

    FROM "sample_catalog"."download_events" AS d

    INNER JOIN target_content AS tc
        ON d.country_code = tc.country_code
       AND d.content_id = tc.content_id

    CROSS JOIN params AS p

    WHERE CAST(d.event_date AS DATE)
          BETWEEN p.start_date AND p.end_date

      AND d.status = 'success'

    GROUP BY
        d.country_code,
        d.content_id
),


/* ---------------------------------------------------------------------------
6. Purchase metrics

Revenue:
    Total successful purchase amount during the analysis period.

PU:
    Unique purchasing users during the analysis period.

ARPPU:
    Revenue / PU
--------------------------------------------------------------------------- */

purchase_metrics AS (

    SELECT
        pch.country_code,
        pch.content_id,

        ROUND(
            SUM(CAST(pch.purchase_amount AS DOUBLE)),
            2
        ) AS revenue,

        COUNT(DISTINCT pch.user_id) AS purchase_users

    FROM "sample_catalog"."purchase_events" AS pch

    INNER JOIN target_content AS tc
        ON pch.country_code = tc.country_code
       AND pch.content_id = tc.content_id

    CROSS JOIN params AS p

    WHERE CAST(pch.event_date AS DATE)
          BETWEEN p.start_date AND p.end_date

      AND pch.status = 'success'

    GROUP BY
        pch.country_code,
        pch.content_id
),


/* ---------------------------------------------------------------------------
7. AU

Count unique users who used each content during the analysis period.
--------------------------------------------------------------------------- */

active_users AS (

    SELECT
        a.country_code,
        a.content_id,
        COUNT(DISTINCT a.user_id) AS au

    FROM "sample_catalog"."content_usage" AS a

    INNER JOIN target_content AS tc
        ON a.country_code = tc.country_code
       AND a.content_id = tc.content_id

    CROSS JOIN params AS p

    WHERE CAST(a.event_date AS DATE)
          BETWEEN p.start_date AND p.end_date

    GROUP BY
        a.country_code,
        a.content_id
),


/* ---------------------------------------------------------------------------
8. Combine metrics

LEFT JOIN from the target list so contents with zero activity are retained.
--------------------------------------------------------------------------- */

content_metrics AS (

    SELECT
        tc.country_code,
        tc.content_id,

        cm.content_name,
        cm.first_sales_date,

        COALESCE(n.nau, 0) AS nau,
        COALESCE(a.au, 0) AS au,

        COALESCE(d.downloads, 0) AS downloads,

        COALESCE(pm.revenue, 0) AS revenue,
        COALESCE(pm.purchase_users, 0) AS purchase_users

    FROM target_content AS tc

    LEFT JOIN content_metadata AS cm
        ON tc.country_code = cm.country_code
       AND tc.content_id = cm.content_id

    LEFT JOIN new_users AS n
        ON tc.country_code = n.country_code
       AND tc.content_id = n.content_id

    LEFT JOIN active_users AS a
        ON tc.country_code = a.country_code
       AND tc.content_id = a.content_id

    LEFT JOIN downloads AS d
        ON tc.country_code = d.country_code
       AND tc.content_id = d.content_id

    LEFT JOIN purchase_metrics AS pm
        ON tc.country_code = pm.country_code
       AND tc.content_id = pm.content_id
)


/* ---------------------------------------------------------------------------
9. Final output
--------------------------------------------------------------------------- */

SELECT
    country_code,
    content_id,
    content_name,
    first_sales_date,

    nau,
    au,

    CAST(nau AS DOUBLE)
        / NULLIF(au, 0) AS nau_ratio,

    downloads,

    revenue,
    purchase_users,

    ROUND(
        revenue / NULLIF(purchase_users, 0),
        2
    ) AS arppu

FROM content_metrics

ORDER BY
    country_code,
    nau_ratio DESC,
    content_id;
